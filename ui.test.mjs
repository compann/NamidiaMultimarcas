import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const context=vm.createContext({PRODUTOS:[{id:'1',nome:'A',categoria:'Futebol',preco:50,tamanhos:['P'],promocao:true},{id:'2',nome:'B',categoria:'Polo',preco:90,tamanhos:['G'],promocao:false}],filtros:{promocao:true,categorias:new Set(),tamanhos:new Set(),ordenar:'recentes'}});
vm.runInContext(html.slice(html.indexOf('function listaFiltrada()'),html.indexOf('/* ---- abas ---- */')),context);
assert.equal(vm.runInContext('listaFiltrada().map(p=>p.id).join(",")',context),'1');
vm.runInContext('filtros.promocao=false; filtros.tamanhos.add("G")',context);
assert.equal(vm.runInContext('listaFiltrada().map(p=>p.id).join(",")',context),'2');
const admin=fs.readFileSync(new URL('./admin.html',import.meta.url),'utf8');
const start=admin.indexOf('function escAdmin('),end=admin.indexOf('\nconst LOGO_SRC');
assert.ok(start>=0,'Conteúdo de produto no painel precisa de escape HTML');
vm.runInContext(admin.slice(start,end),context);
assert.equal(vm.runInContext('escAdmin(\'<img src=x onerror="alert(1)">\')',context),'&lt;img src=x onerror=&quot;alert(1)&quot;&gt;');
console.log('UI: filtro Promoção, tamanhos e proteção contra HTML injetado OK.');
